export function buildRulesText(chatTime?: string): string {
  const timeNote = chatTime ? ` в ${chatTime}` : "";
  return [
    "Как работает бот:",
    "",
    `Каждый вечер${timeNote} открывается окно — нажми одну кнопку:`,
    "💪 Красавчик — чисто",
    "🍺 Оступился — небольшой срыв",
    "💥 Пидорнулся — серьёзный срыв",
    "",
    "Если не нажал ничего — засчитывается «Оступился».",
    "Один одиночный срыв не сбивает серию.",
    "Два срыва подряд — серия прерывается.",
    "Вехи: 7, 14, 30, 60, 90 дней.",
    "",
    "/stats — статистика  /pledge — заявить трезвость  /board — лидерборд",
  ].join("\n");
}
